const fs=require('node:fs');
const path=require('node:path');
const {pathToFileURL}=require('node:url');
const {chromium}=require('C:/Users/benchmark/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
(async()=>{
 const out=process.argv[2],browser=await chromium.launch({headless:true,executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
 const page=await browser.newPage({viewport:{width:1400,height:1100},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(String(e)));
 await page.goto(pathToFileURL(path.join(out,'index.html')).href);
 await page.locator('#matrix tr').last().waitFor();
 if(await page.locator('#matrix tr').count()!==8)throw Error('Expected eight model rows');
 if(await page.locator('#matrix td').count()!==40)throw Error('Expected 8 labels plus 32 condition cells');
 if(await page.locator('#live').isEnabled())await page.locator('#live').uncheck();
 await page.getByRole('button',{name:'応答時間',exact:true}).click();
 if(!(await page.locator('#metric-note').textContent()).includes('中央値'))throw Error('Metric switch failed');
 await page.getByRole('button',{name:'最長応答',exact:true}).click();
 if(!(await page.locator('#matrix').textContent()).includes('分'))throw Error('Longest response display failed');
 await page.getByRole('button',{name:'合計時間',exact:true}).click();
 if(!(await page.locator('#matrix').textContent()).includes('分'))throw Error('Total response time display failed');
 await page.getByRole('button',{name:'打ち切り',exact:true}).click();
 if(!(await page.locator('#matrix').textContent()).includes('6件'))throw Error('Expected six Qwen4 HumanEval ON caps');
 await page.getByRole('button',{name:'成功率',exact:true}).click();
 await page.locator('#model-select').selectOption('lfm');
 if(!(await page.locator('#mode-note').textContent()).includes('思考予算0'))throw Error('LFM2.5 mode qualification absent');
 await page.locator('#suite-select').selectOption('he');
 if(await page.locator('#cases tr').count()!==20)throw Error('HumanEval case count failed');
 await page.locator('#model-select').selectOption('qwen-large');
 await page.locator('#suite-select').selectOption('bfcl');
 if(await page.locator('#cases tr').count()!==80)throw Error('BFCL case count failed');
 await page.locator('#differences').check();
 const changedCases=await page.locator('#cases tr').count();
 await page.locator('#differences').uncheck();
 await page.locator('#cases details').first().locator('summary').click();
 if(!(await page.locator('#cases details').first().getAttribute('open')!==null))throw Error('Case detail failed');
 await page.locator('#cases details').first().locator('summary').click();
 await page.screenshot({path:path.join(out,'matrix-desktop.png'),fullPage:true});
 const desktopOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:path.join(out,'matrix-mobile.png'),fullPage:true});
 const mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
 if(desktopOverflow||mobileOverflow)throw Error('Page-level horizontal overflow');
 if(errors.length)throw Error(errors.join('\n'));
 fs.writeFileSync(path.join(out,'ui-validation.json'),JSON.stringify({passed:true,modelRows:8,conditionCells:32,metricSwitches:true,modeQualification:true,caseTables:true,changedCaseFilter:true,changedCases,expandDetails:true,desktopOverflow,mobileOverflow,jsErrors:errors},null,2));
 console.log('Dashboard UI verified at desktop and mobile sizes.');await browser.close();
})().catch(e=>{console.error(e);process.exitCode=1});
